// themeAt 은 번호가 범위를 벗어나도 기본 테마를 돌려준다.
func themeAt(i int) windowTheme {
	if i < 0 || i >= len(windowThemes) {
		return windowThemes[0]
	}
	return windowThemes[i]
}

// mix 는 두 색을 t(0~1) 비율로 섞는다.
func mix(a, b uint32, t float64) uint32 {
	ch := func(c uint32, s uint) float64 { return float64((c >> s) & 0xFF) }
	out := uint32(0)
	for _, s := range []uint{16, 8, 0} {
		out |= uint32(ch(a, s)*(1-t)+ch(b, s)*t+0.5) << s
	}
	return out
}
